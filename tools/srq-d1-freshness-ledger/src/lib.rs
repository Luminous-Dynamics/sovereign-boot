    #[test]
    fn concurrent_replay_has_exactly_one_winner() {
        const THREADS: usize = 64;
        let ledger = Arc::new(ledger());
        issue_default(&ledger);
        let barrier = Arc::new(Barrier::new(THREADS));
        let mut handles = Vec::with_capacity(THREADS);
        for _ in 0..THREADS {
            let ledger = Arc::clone(&ledger);
            let barrier = Arc::clone(&barrier);
            let candidate = evidence();
            handles.push(thread::spawn(move || {
                barrier.wait();
                ledger.consume(candidate, 120, 21_000_000_000)
            }));
        }

        let results: Vec<_> = handles
            .into_iter()
            .map(|handle| handle.join().unwrap())
            .collect();
        let accepted = results.iter().filter(|result| result.is_ok()).count();
        let replay_rejected = results
            .iter()
            .filter(|result| **result == Err(LedgerError::ChallengeAlreadyConsumed))
            .count();
        assert_eq!(accepted, 1);
        assert_eq!(replay_rejected, THREADS - 1);
    }
